comment on table public.cooking_catalog_items is 'V1 ingredient and meal references. Not an inventory; ingredient acquisition and artwork may be unresolved. No implicit mapping from plural crops or bundles to individual ingredients.';
create table public.cooking_activities(
 id text primary key,name text not null unique,
 skill_id text not null default 'cooking' check(skill_id='cooking'),
 category text not null check(category in('standard','everyday','artisan','master')),
 specialization_id text,required_level integer not null check(required_level between 1 and 99),
 required_branch_level integer check(required_branch_level between 1 and 99),
 time_reduction_percent integer not null check(time_reduction_percent between 1 and 99),
 food_eligibility text not null check(food_eligibility in('general-activity','pending-profession')),
 eligible_skill_id text references public.skill_types(id),
 check(eligible_skill_id is null),
 check((category='artisan' and food_eligibility='pending-profession') or (category<>'artisan' and food_eligibility='general-activity')),
 duration_seconds integer not null check(duration_seconds>0),
 cooking_xp integer not null check(cooking_xp>0),branch_xp integer not null check(branch_xp>=0),
 output_item_id text not null references public.cooking_catalog_items(id),
 yield_quantity integer not null check(yield_quantity>0),
 sort_order integer not null unique,
 status text not null default 'planned' check(status in('planned','disabled')),
 balance_status text not null default 'draft' check(balance_status='draft'),
 source_version text not null default 'cooking-v1' check(source_version='cooking-v1'),
 foreign key(skill_id,specialization_id) references public.skill_specializations(skill_id,id),
 check((category='standard' and specialization_id is null and required_branch_level is null and branch_xp=0)
 or (category<>'standard' and specialization_id is not null and required_branch_level is not null and branch_xp>0 and (
 (category='everyday' and specialization_id='everyday-chef' and required_level>=10) or
 (category='artisan' and specialization_id='artisan-chef' and required_level>=30) or
 (category='master' and specialization_id='master-chef' and required_level>=30))))
);
create index cooking_activities_branch on public.cooking_activities(skill_id,specialization_id);
create index cooking_activities_output on public.cooking_activities(output_item_id);
create table public.cooking_activity_inputs(
 activity_id text not null references public.cooking_activities(id) on delete cascade,
 item_id text not null references public.cooking_catalog_items(id),quantity integer not null check(quantity>0),primary key(activity_id,item_id)
);
create index cooking_inputs_item on public.cooking_activity_inputs(item_id);
create table public.cooking_activity_runes(
 activity_id text not null references public.cooking_activities(id) on delete cascade,
 rune_id text not null references public.rune_types(id),quantity integer not null check(quantity>0),primary key(activity_id,rune_id)
);
create index cooking_runes_type on public.cooking_activity_runes(rune_id);
