create table public.crafting_catalog_items(id text primary key,name text not null unique);
comment on table public.crafting_catalog_items is 'V1 material and output references. Not inventory. Source links, acquisition, tradeability, caps, equipment modifiers and artwork remain pending. No implicit batch-to-item conversions.';
create table public.crafting_activities(
 id text primary key,name text not null unique,
 skill_id text not null default 'crafting' check(skill_id='crafting'),
 category text not null check(category in('standard','jewelry','utility','decorative')),
 specialization_id text,required_level integer not null check(required_level between 1 and 99),
 required_branch_level integer check(required_branch_level between 1 and 99),
 equipment text[] not null check(cardinality(equipment)>0),
 requires_consumption_confirmation boolean not null default false,
 duration_seconds integer not null check(duration_seconds>0),
 crafting_xp integer not null check(crafting_xp>0),branch_xp integer not null check(branch_xp>=0),
 check(requires_consumption_confirmation=(category='decorative')),
 output_item_id text not null references public.crafting_catalog_items(id),
 yield_quantity integer not null check(yield_quantity>0),
 sort_order integer not null unique,
 status text not null default 'planned' check(status in('planned','disabled')),
 balance_status text not null default 'draft' check(balance_status='draft'),
 source_version text not null default 'crafting-v1' check(source_version='crafting-v1'),
 foreign key(skill_id,specialization_id) references public.skill_specializations(skill_id,id),
 check((category='standard' and specialization_id is null and required_branch_level is null and branch_xp=0)
 or (category<>'standard' and specialization_id is not null and required_branch_level is not null and branch_xp>0 and (
 (category='jewelry' and specialization_id='jeweler' and required_level>=10) or
 (category='utility' and specialization_id='utility-crafting' and required_level>=30) or
 (category='decorative' and specialization_id='decorative-collectibles' and required_level>=30))))
);
create index crafting_activities_branch on public.crafting_activities(skill_id,specialization_id);
create index crafting_activities_output on public.crafting_activities(output_item_id);
create table public.crafting_activity_inputs(
 activity_id text not null references public.crafting_activities(id) on delete cascade,
 item_id text not null references public.crafting_catalog_items(id),quantity integer not null check(quantity>0),primary key(activity_id,item_id)
);
create index crafting_inputs_item on public.crafting_activity_inputs(item_id);
create table public.crafting_activity_runes(
 activity_id text not null references public.crafting_activities(id) on delete cascade,
 rune_id text not null references public.rune_types(id),quantity integer not null check(quantity>0),primary key(activity_id,rune_id)
);
create index crafting_runes_type on public.crafting_activity_runes(rune_id);
comment on table public.crafting_activities is 'Crafting V1 draft: costs, yields and XP per completed batch. One active skill/service; passive runes independent. Profession equipment has no assigned combat, speed or yield modifiers. Training, success probabilities, reservations, cancellations, refunds and ledger settlement remain pending. Decorative recipes require confirmation before irreversible input consumption. No inventory is consumed by this catalog.';
