create function public.sync_farming_level() returns trigger language plpgsql security invoker set search_path='' as $$
begin
 if new.skill_id='farming' and new.xp>=0 then new.level=public.farming_level_for_xp(new.xp); end if;
 return new;
end $$;
revoke all on function public.sync_farming_level() from public,anon,authenticated;
