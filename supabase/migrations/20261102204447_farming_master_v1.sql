create table public.farming_activities(
 id text primary key,name text not null unique,
 skill_id text not null default 'farming' check(skill_id='farming'),
 category text not null check(category in('standard','crop','herbalism','rare-plant')),
 specialization_id text,required_level integer not null check(required_level between 1 and 99),
 required_branch_level integer check(required_branch_level between 1 and 99),
 equipment_requirement text not null check(length(equipment_requirement)>0),
 duration_seconds integer not null check(duration_seconds>0),
 farming_xp integer not null check(farming_xp>0),branch_xp integer not null check(branch_xp>=0),
 output_item_id text not null references public.farming_catalog_items(id),
 yield_quantity integer not null check(yield_quantity>0),
 sort_order integer not null unique,
 status text not null default 'planned' check(status in('planned','disabled')),
 balance_status text not null default 'draft' check(balance_status='draft'),
 source_version text not null default 'farming-v1' check(source_version='farming-v1'),
 foreign key(skill_id,specialization_id) references public.skill_specializations(skill_id,id),
 check((category='standard' and specialization_id is null and required_branch_level is null and branch_xp=0)
 or (category<>'standard' and specialization_id is not null and required_branch_level is not null and branch_xp>0 and (
 (category='crop' and specialization_id='crop-farming' and required_level>=10) or
 (category='herbalism' and specialization_id='herbalism' and required_level>=30) or
 (category='rare-plant' and specialization_id='rare-plant-cultivation' and required_level>=30))))
);
create index farming_activities_branch on public.farming_activities(skill_id,specialization_id);
create index farming_activities_output on public.farming_activities(output_item_id);
create table public.farming_activity_inputs(
 activity_id text not null references public.farming_activities(id) on delete cascade,
 item_id text not null references public.farming_catalog_items(id),quantity integer not null check(quantity>0),primary key(activity_id,item_id)
);
create index farming_inputs_item on public.farming_activity_inputs(item_id);
create table public.farming_activity_runes(
 activity_id text not null references public.farming_activities(id) on delete cascade,
 rune_id text not null references public.rune_types(id),quantity integer not null check(quantity>0),primary key(activity_id,rune_id)
);
create index farming_runes_type on public.farming_activity_runes(rune_id);
