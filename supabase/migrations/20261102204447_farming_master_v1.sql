create function public.farming_level_for_xp(p_xp bigint) returns integer language sql stable strict security invoker set search_path='' as $$
 select level from public.skill_xp_levels where skill_id='farming' and total_xp<=p_xp order by total_xp desc limit 1
$$;
revoke all on function public.farming_level_for_xp(bigint) from public,anon,authenticated;
grant execute on function public.farming_level_for_xp(bigint) to service_role;
create function public.farming_branch_level_for_xp(p_xp bigint) returns integer language sql stable strict security invoker set search_path='' as $$
 select level from public.farming_branch_xp_levels where total_xp<=p_xp order by total_xp desc limit 1
$$;
revoke all on function public.farming_branch_level_for_xp(bigint) from public,anon,authenticated;
