create table public.smithing_catalog_items(id text primary key,name text not null unique);
comment on table public.smithing_catalog_items is 'V1 material and output references. Not inventory. Source links, acquisition, tradeability, caps, equipment modifiers and artwork remain pending. No implicit batch-to-item conversions.';
create table public.smithing_activities(
 id text primary key,name text not null unique,
 skill_id text not null default 'smithing' check(skill_id='smithing'),
 category text not null check(category in('standard','toolsmith','artisan','masterwork')),
 specialization_id text,required_level integer not null check(required_level between 1 and 99),
 required_branch_level integer check(required_branch_level between 1 and 99),
 duration_seconds integer not null check(duration_seconds>0),
 smithing_xp integer not null check(smithing_xp>0),branch_xp integer not null check(branch_xp>=0),
 output_item_id text not null references public.smithing_catalog_items(id),
 yield_quantity integer not null check(yield_quantity>0),
 sort_order integer not null unique,
 status text not null default 'planned' check(status in('planned','disabled')),
 balance_status text not null default 'draft' check(balance_status='draft'),
 source_version text not null default 'smithing-v1' check(source_version='smithing-v1'),
 foreign key(skill_id,specialization_id) references public.skill_specializations(skill_id,id),
 check((category='standard' and specialization_id is null and required_branch_level is null and branch_xp=0)
 or (category<>'standard' and specialization_id is not null and required_branch_level is not null and branch_xp>0 and (
 (category='toolsmith' and specialization_id='toolsmith' and required_level>=10) or
 (category='artisan' and specialization_id='artisan-equipment' and required_level>=30) or
 (category='masterwork' and specialization_id='masterwork-forging' and required_level>=30))))
);
create index smithing_activities_branch on public.smithing_activities(skill_id,specialization_id);
create index smithing_activities_output on public.smithing_activities(output_item_id);
create table public.smithing_activity_inputs(
 activity_id text not null references public.smithing_activities(id) on delete cascade,
 item_id text not null references public.smithing_catalog_items(id),quantity integer not null check(quantity>0),primary key(activity_id,item_id)
);
create index smithing_inputs_item on public.smithing_activity_inputs(item_id);
create table public.smithing_activity_runes(
 activity_id text not null references public.smithing_activities(id) on delete cascade,
 rune_id text not null references public.rune_types(id),quantity integer not null check(quantity>0),primary key(activity_id,rune_id)
);
create index smithing_runes_type on public.smithing_activity_runes(rune_id);
