create function public.smithing_level_for_xp(p_xp bigint) returns integer language sql stable strict security invoker set search_path='' as $$
 select level from public.skill_xp_levels where skill_id='smithing' and total_xp<=p_xp order by total_xp desc limit 1
$$;
